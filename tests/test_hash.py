from cryptography.hazmat.primitives import hashes

def test_hash(hash:str, size:int, message: str) -> str:
    # Initialize a hash context using SHA-256
    digest = hashes.Hash(hashes.Provided(hash, size, 32))
    
    # Update the hash object with the bytes of the message
    digest.update(bytes.fromhex(message))
    
    # Finalize the hash and return it as a hexadecimal string
    hashed_bytes = digest.finalize()
    return hashed_bytes.hex()

def test(name:str, a:str, b:str):
    if a.upper() == b.upper():
        print(f"Test {name}: true")
    else:
        print(f"A:{a}")
        print(f"B:{b}")
        print(f"Test {name}: false")

